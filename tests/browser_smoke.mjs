// Real-browser smoke test for the public, fictional RecVerity demo.
// Executed by GitHub Actions on a local HTTP server, without paid services.
import {chromium} from "playwright";
import {mkdir} from "node:fs/promises";
import assert from "node:assert/strict";
const errors=[];
await mkdir("artifacts",{recursive:true});
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 page.on("pageerror",e=>errors.push(e.message));
 const response=await page.goto("http://127.0.0.1:8000/",{waitUntil:"networkidle"});
 assert.equal(response.status(),200);
 await page.locator("#overview h1").waitFor();
 assert.match(await page.title(),/RecVerity/);
 await page.screenshot({path:"artifacts/desktop-overview.png",fullPage:true});
 await page.locator("a[href='#lab']").first().click();
 await page.locator("#results .product").first().waitFor();
 assert.equal(await page.locator("#results .product").count(),5);
 await page.locator("#weight").evaluate(el=>{el.value="30";el.dispatchEvent(new Event("input",{bubbles:true}));});
 assert.match(await page.locator("#weight-value").innerText(),/30% CF/);
 await page.locator("#persona").selectOption("guest");
 assert.match(await page.locator("#results").innerText(),/popularity fallback/i);
 await page.screenshot({path:"artifacts/desktop-lab.png",fullPage:true});
 await page.locator("a[href='#cold']").first().click();
 await page.locator("#cold-results .product").first().waitFor();
 assert.equal(await page.locator("#cold-results .product").count(),5);
 await page.locator("a[href='#audit']").first().click();
 assert.match(await page.locator("#audit").innerText(),/3\.48%/);
 await page.locator("a[href='#engineering']").first().click();
 assert.match(await page.locator("#engineering").innerText(),/TF-IDF/);
 assert.deepEqual(errors,[]);

 await page.goto("http://127.0.0.1:8000/trust-lab.html",{waitUntil:"networkidle"});
 await page.locator("#drift-checks .qa-check").first().waitFor();
 assert.equal(await page.locator("#drift-checks .qa-check").count(),4);
 await page.locator("#scenario").selectOption("price-shock");
 assert.match(await page.locator("#drift-summary").innerText(),/alert/i);
 await page.locator("#leak-scenario").selectOption("review-reuse");
 assert.match(await page.locator("#leak-results").innerText(),/review event overlap/i);
 await page.locator("#question").fill("Why 81.67 became 3.48?");
 await page.locator("#ask-form button[type=submit]").click();
 assert.ok(await page.locator("#answer .chat-user").count()>=2);
 await page.locator("#ask-clear").click();
 assert.equal(await page.locator("#answer .chat-user").count(),0);
 await page.locator("#events-example").click();
 assert.match(await page.locator("#events-report").innerText(),/Shared event IDs: 1/);
 await page.locator("#catalog-example").click();
 assert.match(await page.locator("#catalog-report").innerText(),/REFERENCE/);
 await page.locator("#ask-sample").click();
 assert.match(await page.locator("#answer").innerText(),/source/i);
 await page.locator("#own-example").click();
 await page.locator("#own-results .qa-recommendation").first().waitFor();
 assert.ok(await page.locator("#own-results .qa-recommendation").count()>=1);
 const ownCatalog="product_id,product_name,category,price,rating,available\np1,Headphones,Audio,1100,4.8,true\np2,<img src=x onerror=alert(1)>,Audio,1300,4.1,true\np3,Notebook,Computing,500,,true\n";
 const ownTraining="user_id,product_id,rating,timestamp,event_id\nu1,p1,5,10,e1\nu2,p1,5,11,e2\nu2,p2,4,12,e3\n";
 const ownTesting="user_id,product_id,rating,timestamp,event_id\nu3,p3,5,15,e2\n";
 await page.locator("#catalog-ref").setInputFiles({name:"reference.csv",mimeType:"text/csv",buffer:Buffer.from(ownCatalog)});
 await page.locator("#events-train").setInputFiles({name:"train.csv",mimeType:"text/csv",buffer:Buffer.from(ownTraining)});
 await page.locator("#events-test").setInputFiles({name:"test.csv",mimeType:"text/csv",buffer:Buffer.from(ownTesting)});
 await page.locator("#events-run").click();
 assert.match(await page.locator("#events-report").innerText(),/Shared event IDs: 1/);
 await page.locator("#own-user").fill("u1");
 await page.locator("#own-run").click();
 await page.locator("#own-results .qa-recommendation").first().waitFor();
 assert.ok(await page.locator("#own-results .qa-recommendation").count()>0);
 assert.equal(await page.locator("#own-results img").count(),0,"CSV output must render as text, never markup");
 await page.locator("#catalog-cur").setInputFiles({name:"current.csv",mimeType:"text/csv",buffer:Buffer.from(ownCatalog.replace("Computing","Audio"))});
 await page.locator("#catalog-run").click();
 assert.match(await page.locator("#catalog-report").innerText(),/DRIFT/);
  await page.screenshot({path:"artifacts/desktop-research-assurance.png",fullPage:true});
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 mobile.on("pageerror",e=>errors.push(e.message));
 await mobile.goto("http://127.0.0.1:8000/",{waitUntil:"networkidle"});
 await mobile.locator("#overview h1").waitFor();
 await mobile.locator("#menu").click();
 assert.equal(await mobile.locator("#mobile-links").isVisible(),true);
 await mobile.locator("#mobile-links a[href='#lab']").click();
 await mobile.locator("#results .product").first().waitFor();
 assert.equal(await mobile.locator("#results .product").count(),5);
 await mobile.screenshot({path:"artifacts/mobile-lab.png",fullPage:true});
 await mobile.goto("http://127.0.0.1:8000/trust-lab.html",{waitUntil:"networkidle"});
 await mobile.locator("#menu").click();
 await mobile.locator("#mobile-links a[href='#csv']").click();
 await mobile.locator("#catalog-run").waitFor();
 await mobile.screenshot({path:"artifacts/mobile-research-assurance.png",fullPage:true});
 assert.deepEqual(errors,[]);
 console.log("PASS desktop/mobile navigation, ranking, guest fallback, cold start, audit and browser errors");
}finally{await browser.close();}
